def read_flat_yaml(path):
    """korp-vue's locale files are flat `key: value` lines."""
    strings = {}
    for line in Path(path).read_text().splitlines():
        m = re.match(r"^([A-Za-z0-9_.\-]+):\s*(.*)$", line)
        if m:
            value = m.group(2).strip()
            if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
                value = value[1:-1]
            strings[m.group(1)] = value
    return strings


def vue_i18n_escape(text):
    """vue-i18n gives @ | { } special meaning: escape @ and |, refuse braces."""
    if "{" in text or "}" in text:
        return None
    return text.replace("@", "{'@'}").replace("|", "{'|'}")


def main(vue_eng_path, old_eng_path):
    vue_eng = read_flat_yaml(vue_eng_path)
    old_eng = json.loads(Path(old_eng_path).read_text())
    old_keys_by_text = {}
    for key, text in old_eng.items():
        if isinstance(text, str):
            old_keys_by_text.setdefault(text.strip().lower(), []).append(key)

    for lang in LANGS:
        old = json.loads((TRANSLATIONS / f"locale-{lang}.json").read_text())
        lines = [
            f"# {lang}: generated by port-translations.py from",
            f"# gtweb2_config/translations/locale-{lang}.json. Missing strings fall back to English.",
        ]
        for key, text in vue_eng.items():
            for old_key in old_keys_by_text.get(text.lower(), []):
                translation = old.get(old_key)
                if isinstance(translation, str) and translation.strip():
                    escaped = vue_i18n_escape(translation.strip())
                    if escaped is not None:
                        lines.append(f"{key}: {json.dumps(escaped, ensure_ascii=False)}")
                        break
        for key, text in EXTRA[lang].items():
            lines.append(f"{key}: {json.dumps(text, ensure_ascii=False)}")
        Path("locale", f"{lang}.yaml").write_text("\n".join(lines) + "\n")
        print(f"locale/{lang}.yaml: {len(lines) - 2} of {len(vue_eng)} strings")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(*sys.argv[1:])

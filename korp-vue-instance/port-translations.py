#!/usr/bin/env python3
"""Make korp-vue locale files (locale/<lang>.yaml) from our old korp-frontend
translations (gtweb2_config/translations/locale-<lang>.json).

korp-vue renamed nearly all UI string keys, so translations are matched by
their English text: a korp-vue string whose English text (src/locale/eng.yaml
in korp-vue) is the same as a korp-frontend string's (app/translations/
locale-eng.json in korp-frontend) gets our translation of that string.
Strings without a match fall back to English in the app.

    port-translations.py KORP_VUE_ENG_YAML KORP_FRONTEND_ENG_JSON

Run from korp-vue-instance/. Overwrites locale/{sme,nob,fin,rus}.yaml.
"""

import json
import re
import sys
from pathlib import Path

LANGS = ["sme", "nob", "fin", "rus"]
TRANSLATIONS = Path(__file__).resolve().parent.parent / "gtweb2_config" / "translations"

